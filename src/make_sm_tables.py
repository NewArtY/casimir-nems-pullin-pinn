ZETA_UNIFORM = 2.0 ** -0.25


def _pressure(p):
    """Pressure in Pa, rendered for a table cell."""
    if p is None:
        return "---"
    if p >= 1000:
        return f"${p / 1000:.1f}\\,\\mathrm{{k}}$"
    if p >= 10:
        return f"${p:.0f}$"
    return f"${p:.2g}$"


def _zeta_range(lo, hi):
    """Two damping estimates as one cell: a range, or one value if they agree."""
    spec = ".1f" if lo >= 1 else ".2f"
    a, b = format(lo, spec), format(hi, spec)
    return f"${a}$" if a == b else f"${a}$--${b}$"


