# S1 -- trajectory PINN training protocol
# ---------------------------------------------------------------------------
def table_s1():
    keys = ["stable", "growing", "pullin"]
    cfg, par, wall, loss = {}, {}, {}, {}
    for key in keys:
        h = load_json(LOGS / f"history_{key}.json")
        cfg[key], par[key] = h["config"], h["params"]
        wall[key] = h["wall_time"]
        loss[key] = h["L_total"][-1]

    def row(label, fn):
        return label + " & " + " & ".join(fn(k) for k in keys) + NL

    b = []
    b.append("% generated by code/src/make_sm_tables.py -- do not edit by hand\n")
    b.append("\\begin{table}[htb]\n")
    b.append("\\caption{\\label{tab:S1}%\n")
    b.append("Training protocol of the three single-trajectory physics-informed\n")
    b.append("neural networks. All runs are CPU-only, in double precision, and\n")
    b.append("seeded with $42$. Wall-clock times were measured on one core.\n")
    b.append("The delayed-pull-in network is archived under the name\n")
    b.append("\\texttt{growing}; its window ends before the collapse.}\n")
    b.append("\\begin{ruledtabular}\n")
    b.append("\\begin{tabular}{lccc}\n")
    b.append("Setting & Stable & Delayed pull-in & Pull-in" + NL + COLRULE)
    b.append(row("Parametrization", lambda k: cfg[k]["parametrization"]))
    b.append(row("$\\alpha$", lambda k: f"${par[k]['alpha']:.6g}$"))
    b.append(row("$\\beta$", lambda k: sci(par[k]["beta"], 3)
                 if par[k]["beta"] < 1e-2 else f"${par[k]['beta']:.6g}$"))
    b.append(row("$\\zeta$", lambda k: f"${par[k]['zeta']:g}$"))
    b.append(row("Training window $T$", lambda k: f"${par[k]['T']:.4g}$"))
    b.append(row("Hidden layers", lambda k: integer(cfg[k]["n_hidden"])))
    b.append(row("Width", lambda k: integer(cfg[k]["width"])))
    b.append(row("Fourier modes", lambda k: integer(cfg[k]["n_fourier"])))
    b.append(row("Fourier $\\omega$", lambda k: f"${cfg[k]['fourier_omega']:g}$"))
    b.append(row("Collocation $N$", lambda k: integer(cfg[k]["n_collocation"])))
    b.append(row("Adam steps", lambda k: integer(cfg[k]["adam_iters"])))
    b.append(row("Adam rate", lambda k: sci(cfg[k]["adam_lr"], 1)))
    b.append(row("L-BFGS steps", lambda k: integer(cfg[k]["lbfgs_iters"])))
