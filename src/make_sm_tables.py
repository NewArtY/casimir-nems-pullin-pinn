ZETA_C0 = 0.395919          # zeta_c at beta = 0, Appendix B


def band_fit():
    """Ratio w/(zeta_c - zeta)^2 and its limit at zeta_c.

    The limit is the intercept of a straight-line fit of the ratio against
    zeta_c - zeta over zeta >= 0.30, where the ratio is linear to the
    plotting accuracy.
    """
    band = load_json(RESULTS / "threshold_checks.json")["band_beta0"]
    z = np.array([r["zeta"] for r in band])
    w = np.array([r["width_manifold"] for r in band])
    ratio = w / (ZETA_C0 - z) ** 2
    sel = z >= 0.30
    slope, C0 = np.polyfit(ZETA_C0 - z[sel], ratio[sel], 1)
    return band, ratio, float(C0), float(slope)


