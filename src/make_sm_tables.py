def sci(x, sig=2):
    """Render x as $m\\times10^{e}$ with `sig` significant digits."""
    if x is None:
        return "---"
    if x == 0:
        return "$0$"
    s = f"{x:.{sig}e}"
    mant, exp = s.split("e")
    exp = int(exp)
    if exp == 0:
        return f"${mant}$"
    return "$" + mant + r"\times10^{" + str(exp) + "}$"


def integer(x):
    return "---" if x is None else f"${int(x)}$"


def write(name, body):
    path = OUT / name
    path.write_text(body, encoding="ascii", newline="\n")
    print(f"wrote {path.name}  ({len(body)} chars)")


def load_json(p):
    with open(p, encoding="utf-8") as fh:
        return json.load(fh)


NL = "\\\\\n"
COLRULE = "\\colrule\n"


